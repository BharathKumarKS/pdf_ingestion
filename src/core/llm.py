"""
Shared LLM caller — routes to Ollama or an OpenAI-compatible cluster.

All Phase 2 + Phase 3 LLM calls (card generation, RAPTOR summaries,
concept extraction) go through call_llm() so switching backends is a
single .env change:

  LLM_BACKEND=ollama   →  POST /api/generate   (Ollama format)
  LLM_BACKEND=openai   →  POST /v1/chat/completions  (OpenAI format)

The OpenAI path works with any OpenAI-compatible server:
  vLLM, LiteLLM, Together AI, Anyscale, Azure OpenAI, etc.
No ollama pull, no ollama serve — just point OPENAI_API_BASE at your
cluster endpoint and set OPENAI_MODEL to whatever the server exposes.

Retry + total-request deadline (IMPROVEMENTS.md §I24)
----------------------------------------------------
This module used to issue **one un-retried POST** with `timeout=OLLAMA_TIMEOUT`
(120 s) and return `""` on any failure. That is the defect §I16 fixed in the
embedding path, still present here — and here it costs more, because this is the
caller for cards, RAPTOR summaries, concept extraction, HyDE and the judge.

httpx's read timeout is **per read operation, not per request**: a response body
that keeps trickling resets the timer on every chunk, so a stalled-but-alive
transfer outlives any read timeout. Measured cost (Phase B card run, 2026-10-19):
chunks 69-70's card calls all timed out at 22:12:42-44, then **no log line at all
until 22:53:48** — a 41-minute silent window inside requests the 120 s read
timeout could not bound, and which the retry (there was none) could not catch.

So a request is now:
  * read in chunks against a **wall-clock deadline** (`_LLM_DEADLINE`), raised as
    `httpx.ReadTimeout` so the retry treats it as transient; and
  * retried a bounded number of times with jittered backoff on transport errors,
    429 and 5xx — never on other 4xx, which would fail identically every time.

The failure contract is unchanged: `call_llm` returns `""` on failure and logs at
ERROR, and callers must not treat `""` as a valid answer. What is new is that
failures are **counted** (`llm_call_stats()`), so a phase can assert on them
instead of inferring health from a log line that a swallowed exception never
prints (§I25).
"""
from __future__ import annotations

import json
import random
import threading
import time

import httpx
from loguru import logger

from src.core.config import Settings, get_settings

# -- Retry / deadline policy ---------------------------------------------------
# Same shape as the §I16 fix in `cluster_embedder`, sized for a generation call
# rather than an embedding one.
#
# `_LLM_DEADLINE` is the TOTAL wall-clock budget for one request — the thing no read
# timeout provides. A healthy `openai/gpt-oss-20b` card call measures ~10 s
# (Phase B's B1 probe: 7.6 / 10.9 / 10.1 s per chunk of 8 card types), so 300 s is
# ~30x headroom: generous enough that a slow-but-healthy call is not cut off, and
# bounded enough that the 41-minute stall cannot recur. A caller that passes an
# explicit `timeout` longer than this keeps its own budget (see `_budget`).
_LLM_DEADLINE = 300.0
_CONNECT_TIMEOUT = 10.0      # fail fast on an unreachable host instead of waiting out the read

# Retryable = the request could plausibly succeed if repeated: transport-level
# failures (timeouts, connect/reset — `httpx.TransportError` is their common parent),
# HTTP 429, and 5xx. NOT retryable: other 4xx — a malformed request or a wrong model
# name fails identically every time, and retrying only delays a loud error.
_LLM_RETRY_ATTEMPTS = 3      # 1 initial attempt + 2 retries
_LLM_RETRY_BACKOFF = 2.0     # seconds, doubling per attempt, jittered

# -- Failure accounting --------------------------------------------------------
# Cards/RAPTOR/concepts are generated by the thousand and a failed call returns "",
# which several parsers legitimately map to "no card for this type". That makes a
# total endpoint outage indistinguishable from a quiet chunk unless something counts
# (§I25). A lock because the card generator calls this from 8+ threads at once.
_STATS_LOCK = threading.Lock()
_STATS: dict[str, int] = {"calls": 0, "failures": 0, "retries": 0, "deadline_hits": 0}


def llm_call_stats() -> dict[str, int]:
    """Snapshot of this process's LLM call accounting. Never raises."""
    with _STATS_LOCK:
        return dict(_STATS)


def reset_llm_call_stats() -> None:
    """Zero the counters (tests, and the start of a measured run)."""
    with _STATS_LOCK:
        for key in _STATS:
            _STATS[key] = 0


def _bump(key: str, by: int = 1) -> None:
    with _STATS_LOCK:
        _STATS[key] = _STATS.get(key, 0) + by


def _budget(timeout: int | float | None) -> float:
    """Total-request budget: the module default, never under an explicit longer timeout."""
    return max(_LLM_DEADLINE, float(timeout or 0))


def call_llm(
    prompt: str,
    system: str = "",
    settings: Settings | None = None,
    timeout: int | None = None,
    json_mode: bool = False,
) -> str:
    """
    Send a prompt to the configured LLM backend and return the response text.

    Args:
        prompt:    User prompt text.
        system:    Optional system message (ignored by some backends).
        settings:  Settings instance; falls back to get_settings().
        timeout:   Override the per-read timeout in seconds. The total-request
                   deadline is the larger of this and the module default, so a
                   caller can extend a budget but not accidentally shorten it.
        json_mode: Request JSON output (format="json" on Ollama;
                   response_format={"type":"json_object"} on OpenAI).

    Returns:
        Raw response string from the model. **Empty string on failure.**

    Note:
        An empty return is indistinguishable from a genuinely empty completion,
        so callers MUST NOT treat "" as a valid answer. Failures are logged at
        ERROR and counted in `llm_call_stats()`; `scripts/evaluate_rag.py` counts
        them in its artifact rather than letting a dead backend look like a clean run.
    """
    cfg = settings or get_settings()

    if cfg.use_stub_llm:
        return "{}"

    t = timeout or cfg.ollama_timeout

    if cfg.llm_backend == "openai":
        return _call_openai(prompt, system, cfg, t, json_mode)
    return _call_ollama(prompt, system, cfg, t, json_mode)


# ── HTTP transport (shared by both backends) ────────────────────────────────

def _retryable(exc: Exception) -> bool:
    """True when a repeat could plausibly succeed — see the policy above."""
    if isinstance(exc, httpx.TransportError):
        # Timeouts, connect errors, read/write errors, protocol errors.
        return True
    if isinstance(exc, httpx.HTTPStatusError):
        code = exc.response.status_code
        return code == 429 or code >= 500
    return False


def _post_json(client: httpx.Client, url: str, payload: dict, headers: dict,
               timeout: float, deadline_s: float) -> dict:
    """POST and read the **whole** body under a wall-clock deadline.

    ``timeout`` bounds one read operation; it does not bound the request. Reading in
    chunks and checking the clock is what actually bounds it (§I16 / §I24).

    The deadline is raised as ``httpx.ReadTimeout`` deliberately: it is a
    ``TransportError``, so the retry treats it as transient and re-issues the request
    on a fresh connection rather than aborting the caller.
    """
    started = time.monotonic()
    with client.stream("POST", url, json=payload, headers=headers, timeout=timeout) as resp:
        resp.raise_for_status()
        chunks: list[bytes] = []
        for chunk in resp.iter_bytes():
            if time.monotonic() - started > deadline_s:
                _bump("deadline_hits")
                raise httpx.ReadTimeout(
                    f"one LLM request exceeded its {deadline_s:.0f}s total deadline "
                    f"(per-read timeout was {timeout}s, which never fired)",
                    request=resp.request,
                )
            chunks.append(chunk)
    return json.loads(b"".join(chunks))


def _post_with_retry(url: str, payload: dict, headers: dict,
                     timeout: float, deadline_s: float, label: str) -> dict | None:
    """POST with bounded, jittered backoff. Returns the parsed body, or None on failure.

    **Never raises.** None (rather than a raise) because every caller here returns `""` on
    failure and logs at ERROR — the contract callers already depend on, and one that has to hold
    even for a failure that happens before the first attempt (an unreachable host, a bad proxy).
    """
    last: Exception | None = None
    try:
        with httpx.Client(timeout=httpx.Timeout(timeout, connect=_CONNECT_TIMEOUT)) as client:
            for attempt in range(1, _LLM_RETRY_ATTEMPTS + 1):
                try:
                    return _post_json(client, url, payload, headers, timeout, deadline_s)
                except Exception as exc:  # noqa: BLE001 — classified and re-raised below
                    last = exc
                    if attempt >= _LLM_RETRY_ATTEMPTS or not _retryable(exc):
                        break
                    delay = _LLM_RETRY_BACKOFF * (2 ** (attempt - 1))
                    delay *= 0.5 + random.random()  # jitter: half to 1.5x
                    _bump("retries")
                    logger.warning(
                        "LLM POST to {} failed ({}: {}) — retry {}/{} in {:.1f}s",
                        url, type(exc).__name__, str(exc)[:120],
                        attempt, _LLM_RETRY_ATTEMPTS - 1, delay,
                    )
                    time.sleep(delay)
    except Exception as exc:  # noqa: BLE001 — e.g. the client itself could not be built
        last = exc

    assert last is not None
    _bump("failures")
    logger.error(
        "LLM CALL FAILED ({} @ {}) after {} attempt(s): {}: {} — returning empty "
        "string. Callers must not treat '' as a valid answer.",
        label, url, _LLM_RETRY_ATTEMPTS, type(last).__name__, str(last)[:200],
    )
    return None


# ── Ollama ─────────────────────────────────────────────────────────────────

def _call_ollama(
    prompt: str,
    system: str,
    cfg: Settings,
    timeout: int,
    json_mode: bool,
) -> str:
    payload: dict = {
        "model":  cfg.ollama_model,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.3, "top_p": 0.9},
    }
    if system:
        payload["system"] = system
    if json_mode:
        payload["format"] = "json"

    _bump("calls")
    body = _post_with_retry(
        f"{cfg.ollama_host}/api/generate",
        payload,
        {"Content-Type": "application/json"},
        timeout,
        _budget(timeout),
        f"ollama {cfg.ollama_model}",
    )
    if body is None:
        return ""
    return body.get("response", "")


# ── OpenAI-compatible ──────────────────────────────────────────────────────

def _call_openai(
    prompt: str,
    system: str,
    cfg: Settings,
    timeout: int,
    json_mode: bool,
) -> str:
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    payload: dict = {
        "model":       cfg.openai_model,
        "messages":    messages,
        "temperature": 0.3,
        "top_p":       0.9,
    }
    if json_mode:
        payload["response_format"] = {"type": "json_object"}

    headers = {"Content-Type": "application/json"}
    if cfg.openai_api_key and cfg.openai_api_key.lower() != "none":
        headers["Authorization"] = f"Bearer {cfg.openai_api_key}"

    # Strip trailing /v1 if already included in base_url to avoid double /v1
    base = cfg.openai_api_base.rstrip("/")
    if base.endswith("/v1"):
        base = base[:-3]

    url = f"{base}/v1/chat/completions"
    _bump("calls")
    body = _post_with_retry(
        url, payload, headers, timeout, _budget(timeout),
        f"openai {cfg.openai_model}",
    )
    if body is None:
        return ""

    choices = body.get("choices", [])
    if not choices:
        _bump("failures")
        logger.error(
            "LLM CALL FAILED (openai {} @ {}): HTTP 200 with no choices in the "
            "response — returning empty string.",
            cfg.openai_model, cfg.openai_api_base,
        )
        return ""
    return choices[0].get("message", {}).get("content", "")
